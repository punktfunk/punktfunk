//! Compiles `messages/` into `$OUT_DIR/messages.rs`: a module per part this build enables, a
//! function per message, and every shipped language as static data. The format is `SPEC.md`.
//! A file that breaks it fails the build with one line per problem.

#[allow(dead_code)]
#[path = "src/catalog.rs"]
mod catalog;
#[allow(dead_code)]
#[path = "src/json.rs"]
mod json;
#[allow(dead_code)]
#[path = "src/plural.rs"]
mod plural;

use std::fmt::Write as _;
use std::path::PathBuf;
use std::{env, fs};

use catalog::{Catalog, Compiled, Ix, Message};

/// The generated language for finding text that skips this crate (`pseudo` feature).
const PSEUDO: &str = "en-XA";

fn main() {
    let root = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    for path in [
        "messages",
        "locales.json",
        "rules.json",
        "src/catalog.rs",
        "src/json.rs",
    ] {
        println!("cargo::rerun-if-changed={path}");
    }
    let enabled =
        |part: &str| env::var_os(format!("CARGO_FEATURE_{}", part.to_uppercase())).is_some();
    let pseudo = env::var_os("CARGO_FEATURE_PSEUDO").is_some();
    let (cat, mut problems) = catalog::load(&root, false);
    let code = generate(&cat, pseudo, enabled, &mut problems);
    if !problems.is_empty() {
        eprintln!("pf-l10n: messages/ does not compile:");
        for p in &problems {
            eprintln!("  {p}");
        }
        std::process::exit(1);
    }
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR")).join("messages.rs");
    fs::write(&out, code).expect("write messages.rs");
}

fn generate(
    cat: &Catalog,
    pseudo: bool,
    enabled: impl Fn(&str) -> bool,
    problems: &mut Vec<String>,
) -> String {
    let mut langs: Vec<&str> = cat.shipped.iter().map(String::as_str).collect();
    if pseudo {
        langs.push(PSEUDO);
    }
    let mut out =
        String::from("// Generated by pf-l10n's build.rs from messages/. Do not edit.\n\n");
    let _ = writeln!(out, "static LANGS: &[&str] = &{langs:?};");
    let fallback: Vec<(&str, &str)> = cat
        .fallback
        .iter()
        .map(|(a, b)| (a.as_str(), b.as_str()))
        .collect();
    let _ = writeln!(out, "static FALLBACK: &[(&str, &str)] = &{fallback:?};\n");
    let mut tables = Vec::new();
    for part in &cat.parts {
        if !cat.always.contains(&part.name) && !enabled(&part.name) {
            continue;
        }
        let rows = match cat.rows(std::slice::from_ref(&part.name)) {
            Ok(rows) => rows,
            Err(e) => {
                problems.push(e);
                continue;
            }
        };
        let _ = writeln!(
            out,
            "/// Messages of the `{}` part.\npub mod {} {{",
            part.name, part.name
        );
        for row in &rows {
            let mut bodies: Vec<Option<Compiled>> = cat
                .shipped
                .iter()
                .map(|lang| {
                    row.langs
                        .iter()
                        .find(|(l, _)| l == lang)
                        .map(|(_, c)| c.clone())
                })
                .collect();
            if pseudo {
                bodies.push(bodies[0].as_ref().map(|c| accent(c, &row.en.args())));
            }
            message(&mut out, row.key, row.en, &bodies);
        }
        let all: Vec<String> = rows
            .iter()
            .map(|r| format!("&{}", r.key.to_uppercase()))
            .collect();
        let _ = writeln!(
            out,
            "    pub(crate) static ALL: &[&crate::Message] = &[{}];\n}}\n",
            all.join(", ")
        );
        tables.push(format!("{}::ALL", part.name));
    }
    let _ = writeln!(
        out,
        "static PARTS: &[&[&Message]] = &[{}];",
        tables.join(", ")
    );
    out
}

fn message(out: &mut String, key: &str, msg: &Message, bodies: &[Option<Compiled>]) {
    let args = msg.args();
    let count = msg.count().and_then(|c| args.iter().position(|a| a == c));
    let langs: Vec<String> = bodies
        .iter()
        .map(|b| {
            b.as_ref()
                .map_or("None".into(), |b| format!("Some({})", body(b)))
        })
        .collect();
    let name = key.to_uppercase();
    let _ = writeln!(
        out,
        "    static {name}: crate::Message = crate::Message {{ key: {key:?}, args: &{args:?}, count: {count:?}, langs: &[{}] }};",
        langs.join(", ")
    );
    let doc = match msg {
        Message::Plural { cases, .. } => cases
            .iter()
            .find(|(c, _)| *c == plural::Category::Other)
            .map_or(String::new(), |(_, p)| {
                format!("{} (plural)", catalog::display(p))
            }),
        Message::Plain(p) => catalog::display(p),
        Message::Loose { .. } => String::new(),
    };
    let _ = writeln!(out, "    #[doc = {doc:?}]");
    if args.is_empty() && matches!(msg, Message::Plain(_)) {
        let _ = writeln!(
            out,
            "    pub fn {key}() -> &'static str {{ crate::text(&{name}) }}"
        );
        return;
    }
    let params: Vec<String> = args
        .iter()
        .enumerate()
        .map(|(i, a)| {
            if count == Some(i) {
                format!("{a}: u64")
            } else {
                format!("{a}: impl ::core::fmt::Display")
            }
        })
        .collect();
    let refs: Vec<String> = args.iter().map(|a| format!("&{a}")).collect();
    let count_arg = count.map_or("None".into(), |i| format!("Some({})", args[i]));
    let _ = writeln!(
        out,
        "    pub fn {key}({}) -> ::std::string::String {{ crate::format(&{name}, {count_arg}, &[{}]) }}",
        params.join(", "),
        refs.join(", ")
    );
}

fn body(c: &Compiled) -> String {
    let segs = |ix: &[Ix]| {
        let items: Vec<String> = ix
            .iter()
            .map(|i| match i {
                Ix::Text(t) => format!("crate::Seg::Text({t:?})"),
                Ix::Arg(n) => format!("crate::Seg::Arg({n})"),
            })
            .collect();
        format!("&[{}]", items.join(", "))
    };
    match c {
        Compiled::Plain(ix) => format!("crate::Body::Plain({})", segs(ix)),
        Compiled::Plural(cases) => {
            let cases: Vec<String> = cases
                .iter()
                .map(|(cat, ix)| format!("(crate::Category::{cat:?}, {})", segs(ix)))
                .collect();
            format!("crate::Body::Plural(&[{}])", cases.join(", "))
        }
    }
}

/// `en-XA`: letters accented, a third longer, in brackets; placeholders untouched. Only
/// Latin-1 and Latin Extended-A, which the console kit's font draws.
fn accent(c: &Compiled, args: &[String]) -> Compiled {
    const FROM: &str = "acdeghijklnorstuwyzACDEGHIJKLNORSTUWYZ";
    const TO: &str = "áçďéğĥíĵķĺñöŕšťüŵýžÁÇĎÉĞĤÍĴĶĹÑÖŔŠŤÜŴÝŽ";
    let one = |ix: &[Ix]| -> Vec<Ix> {
        let len: usize = ix
            .iter()
            .map(|i| match i {
                Ix::Text(t) => t.chars().count(),
                Ix::Arg(n) => args[*n].len() + 2,
            })
            .sum();
        let mut out = vec![Ix::Text("[".into())];
        let push = |out: &mut Vec<Ix>, s: String| match out.last_mut() {
            Some(Ix::Text(last)) => last.push_str(&s),
            _ => out.push(Ix::Text(s)),
        };
        for i in ix {
            match i {
                Ix::Text(t) => {
                    let s = t
                        .chars()
                        .map(|ch| {
                            FROM.chars()
                                .position(|f| f == ch)
                                .and_then(|p| TO.chars().nth(p))
                                .unwrap_or(ch)
                        })
                        .collect();
                    push(&mut out, s);
                }
                Ix::Arg(n) => out.push(Ix::Arg(*n)),
            }
        }
        push(&mut out, format!(" {}]", "~".repeat(len.div_ceil(3))));
        out
    };
    match c {
        Compiled::Plain(ix) => Compiled::Plain(one(ix)),
        Compiled::Plural(cases) => {
            Compiled::Plural(cases.iter().map(|(k, ix)| (*k, one(ix))).collect())
        }
    }
}
