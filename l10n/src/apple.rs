//! `pf-l10n apple`: `Localizable.xcstrings` and `L10n.swift` for the `PunktfunkShared` module.
//!
//! `L10n` has one accessor per message, named in camelCase. A message without placeholders is
//! a `LocalizedStringResource`: `Text(L10n.playerStatsScalePct)`, or
//! `String(localized: L10n.playerStatsScalePct)` where a `String` is needed. A message with
//! placeholders is a function returning a `String`, one labelled parameter per placeholder in
//! English order, a plural's count as `Int`: `L10n.prefsAdvancedChanged(count: n)`. It is a
//! `String` because `Text` reads Markdown in a resource's arguments, and a host name is not
//! Markdown.
//!
//! The catalog keys each entry by message key and marks it manual, so Xcode never edits or
//! drops it. A plural is a substitution over its count with an explicit argument number, so a
//! variant need not show the number. The accessor passes every argument in index order; the
//! catalog's `%N$` picks them out.
//!
//! Two more catalogs hold text the system reads outside the app's code. `AppShortcuts.xcstrings`
//! is keyed by the English phrase a `PunktfunkShortcuts` literal spells, `{host}` written
//! `${host}`; it comes from the `apple_shortcut_*_phrase` messages. `InfoPlist.xcstrings` is
//! keyed by Info.plist key; `USAGE` says which message fills which.

use std::fmt::Write as _;

use crate::catalog::{self, Catalog, Compiled, Ix, Row};
use crate::json::Json;

/// The usage description messages and the Info.plist keys each one fills.
const USAGE: [(&str, &[&str]); 4] = [
    (
        "apple_usage_local_network",
        &["NSLocalNetworkUsageDescription"],
    ),
    ("apple_usage_microphone", &["NSMicrophoneUsageDescription"]),
    ("apple_usage_face_id", &["NSFaceIDUsageDescription"]),
    (
        "apple_usage_bluetooth",
        &[
            "NSBluetoothAlwaysUsageDescription",
            "NSBluetoothPeripheralUsageDescription",
        ],
    ),
];

/// `(file name, contents)` for each file. The two system catalogs are there when the parts
/// hold their messages.
pub fn generate(cat: &Catalog, parts: &[String]) -> Result<Vec<(String, String)>, String> {
    let rows = cat.rows(parts)?;
    let mut strings = Vec::new();
    let mut swift = String::from(
        "// Generated by pf-l10n from l10n/messages. Do not edit.\n// l10n/src/apple.rs says how to look a message up.\nimport Foundation\n\npublic enum L10n {\n",
    );
    let mut names: Vec<(String, &str)> = Vec::new();
    for row in &rows {
        let name = camel(row.key);
        if let Some((_, other)) = names.iter().find(|(n, _)| *n == name) {
            return Err(format!(
                "{} and {other} are both L10n.{name} in Swift",
                row.key
            ));
        }
        names.push((name.clone(), row.key));
        strings.push((row.key.to_owned(), entry(row, &cat.shipped)));
        accessor(&mut swift, row, &name)?;
    }
    swift.push_str(
        "    private static let bundle = LocalizedStringResource.BundleDescription.atURL(Bundle.module.bundleURL)\n}\n",
    );
    let catalog = Json::Obj(vec![
        ("sourceLanguage".into(), Json::Str(cat.source.clone())),
        ("strings".into(), Json::Obj(strings)),
        ("version".into(), Json::Str("1.0".into())),
    ]);
    let mut files = vec![
        (
            "Localizable.xcstrings".into(),
            crate::json::pretty(&catalog),
        ),
        ("L10n.swift".into(), swift),
    ];
    if let Some(table) = app_shortcuts(&rows, cat)? {
        files.push(("AppShortcuts.xcstrings".into(), table));
    }
    if let Some(table) = info_plist(&rows, cat)? {
        files.push(("InfoPlist.xcstrings".into(), table));
    }
    Ok(files)
}

/// `AppShortcuts.xcstrings`, or nothing when no part holds a phrase.
fn app_shortcuts(rows: &[Row], cat: &Catalog) -> Result<Option<String>, String> {
    let mut strings: Vec<(String, Json)> = Vec::new();
    for row in rows.iter().filter(|r| is_phrase(r.key)) {
        let args = row.en.args();
        let text = |ix: &[Ix]| {
            ix.iter()
                .map(|i| match i {
                    Ix::Text(t) => t.clone(),
                    Ix::Arg(n) => format!("${{{}}}", camel(&args[*n])),
                })
                .collect::<String>()
        };
        let english = text(plain(row, &row.langs[0].1)?);
        if strings.iter().any(|(k, _)| *k == english) {
            return Err(format!("{} repeats the phrase \"{english}\"", row.key));
        }
        strings.push((english, system_entry(row, &cat.shipped, &text)?));
    }
    Ok((!strings.is_empty()).then(|| table(&cat.source, strings)))
}

/// `InfoPlist.xcstrings`, or nothing when no part holds a usage description. A part that
/// holds some and lacks another is an error: the build would ship a prompt with no words.
fn info_plist(rows: &[Row], cat: &Catalog) -> Result<Option<String>, String> {
    let found: Vec<_> = USAGE
        .iter()
        .filter_map(|(key, plist)| Some((rows.iter().find(|r| r.key == *key)?, *plist)))
        .collect();
    if found.is_empty() {
        return Ok(None);
    }
    if let Some((key, _)) = USAGE
        .iter()
        .find(|(k, _)| !found.iter().any(|(r, _)| r.key == *k))
    {
        return Err(format!("InfoPlist.xcstrings needs the message {key}"));
    }
    let mut strings = Vec::new();
    for (row, plist) in found {
        let text = |ix: &[Ix]| {
            ix.iter()
                .map(|i| match i {
                    Ix::Text(t) => t.as_str(),
                    Ix::Arg(_) => "",
                })
                .collect::<String>()
        };
        if !row.en.args().is_empty() {
            return Err(format!(
                "{} takes a placeholder; a usage description cannot",
                row.key
            ));
        }
        for name in plist {
            strings.push(((*name).to_owned(), system_entry(row, &cat.shipped, &text)?));
        }
    }
    Ok(Some(table(&cat.source, strings)))
}

fn is_phrase(key: &str) -> bool {
    key.starts_with("apple_shortcut_") && key.ends_with("_phrase")
}

/// The plain text of a message a system table takes; a plural has no place there.
fn plain<'a>(row: &Row, c: &'a Compiled) -> Result<&'a [Ix], String> {
    match c {
        Compiled::Plain(ix) => Ok(ix),
        Compiled::Plural(_) => Err(format!(
            "{} is a plural; a system table cannot hold one",
            row.key
        )),
    }
}

/// One entry of a system table: each language the message has, and the English for a
/// shipped language that lacks it (state `new`).
fn system_entry(
    row: &Row,
    shipped: &[String],
    text: &dyn Fn(&[Ix]) -> String,
) -> Result<Json, String> {
    let mut langs: Vec<(String, Json)> = Vec::new();
    for (lang, c) in &row.langs {
        let unit = string_unit(text(plain(row, c)?), "translated");
        langs.push(((*lang).to_owned(), Json::Obj(vec![unit])));
    }
    for lang in shipped
        .iter()
        .filter(|l| !row.langs.iter().any(|(k, _)| k == *l))
    {
        let unit = string_unit(text(plain(row, &row.langs[0].1)?), "new");
        langs.push((lang.clone(), Json::Obj(vec![unit])));
    }
    langs.sort_by(|a, b| a.0.cmp(&b.0));
    let mut entry = Vec::new();
    if let Some(note) = row.note {
        entry.push(("comment".to_owned(), Json::Str(note.to_owned())));
    }
    entry.push(("extractionState".into(), Json::Str("manual".into())));
    entry.push(("localizations".into(), Json::Obj(langs)));
    Ok(Json::Obj(entry))
}

/// A catalog file over `strings`, sorted by key as Xcode writes it.
fn table(source: &str, mut strings: Vec<(String, Json)>) -> String {
    strings.sort_by(|a, b| a.0.cmp(&b.0));
    crate::json::pretty(&Json::Obj(vec![
        ("sourceLanguage".into(), Json::Str(source.to_owned())),
        ("strings".into(), Json::Obj(strings)),
        ("version".into(), Json::Str("1.0".into())),
    ]))
}

/// One catalog entry, its fields in the order Xcode writes them. A shipped language without
/// the message gets the English, state `new`: the compiled table would otherwise hold the key.
fn entry(row: &Row, shipped: &[String]) -> Json {
    let args = row.en.args();
    let count = row
        .en
        .count()
        .and_then(|n| args.iter().position(|a| a == n));
    let formatted = !args.is_empty();
    let mut langs: Vec<(String, Json)> = row
        .langs
        .iter()
        .map(|(lang, c)| ((*lang).to_owned(), unit(c, count, formatted, "translated")))
        .collect();
    for lang in shipped {
        if !row.langs.iter().any(|(l, _)| l == lang) {
            langs.push((lang.clone(), unit(&row.langs[0].1, count, formatted, "new")));
        }
    }
    langs.sort_by(|a, b| a.0.cmp(&b.0));
    let mut entry = Vec::new();
    if let Some(note) = row.note {
        entry.push(("comment".to_owned(), Json::Str(note.to_owned())));
    }
    entry.push(("extractionState".into(), Json::Str("manual".into())));
    entry.push(("localizations".into(), Json::Obj(langs)));
    Json::Obj(entry)
}

/// The `stringUnit` field of a language or of a plural form.
fn string_unit(value: String, state: &str) -> (String, Json) {
    let unit = vec![
        ("state".into(), Json::Str(state.into())),
        ("value".into(), Json::Str(value)),
    ];
    ("stringUnit".into(), Json::Obj(unit))
}

/// One language's entry: a string unit, or for a plural `%#@count@` with the count's
/// substitution. A top-level plural variation would not compile without the number in each
/// variant.
fn unit(c: &Compiled, count: Option<usize>, formatted: bool, state: &str) -> Json {
    match (c, count) {
        (Compiled::Plain(ix), _) => {
            Json::Obj(vec![string_unit(format_string(ix, None, formatted), state)])
        }
        (Compiled::Plural(cases), Some(n)) => {
            let mut cases: Vec<_> = cases.iter().collect();
            cases.sort_by_key(|(c, _)| *c);
            let forms = cases
                .iter()
                .map(|(c, ix)| {
                    let form = string_unit(format_string(ix, count, true), state);
                    (c.name().to_owned(), Json::Obj(vec![form]))
                })
                .collect();
            let sub = Json::Obj(vec![
                ("argNum".into(), Json::Num((n + 1) as f64)),
                ("formatSpecifier".into(), Json::Str("lld".into())),
                (
                    "variations".into(),
                    Json::Obj(vec![("plural".into(), Json::Obj(forms))]),
                ),
            ]);
            Json::Obj(vec![
                string_unit("%#@count@".into(), state),
                (
                    "substitutions".into(),
                    Json::Obj(vec![("count".into(), sub)]),
                ),
            ])
        }
        (Compiled::Plural(_), None) => unreachable!("a plural has a count"),
    }
}

/// `%1$@` for a placeholder, `%arg` for the count inside its substitution; a literal `%`
/// doubles when formatted.
fn format_string(ix: &[Ix], count: Option<usize>, formatted: bool) -> String {
    let mut out = String::new();
    for i in ix {
        match i {
            Ix::Text(t) if formatted => out.push_str(&t.replace('%', "%%")),
            Ix::Text(t) => out.push_str(t),
            Ix::Arg(n) if Some(*n) == count => out.push_str("%arg"),
            Ix::Arg(n) => {
                let _ = write!(out, "%{}$@", n + 1);
            }
        }
    }
    out
}

/// `player_stats_scale_pct` → `playerStatsScalePct`.
fn camel(key: &str) -> String {
    let mut out = String::new();
    for (i, word) in key.split('_').enumerate() {
        let mut chars = word.chars();
        match chars.next() {
            Some(c) if i > 0 => out.extend(c.to_uppercase().chain(chars)),
            Some(c) => out.extend(std::iter::once(c).chain(chars)),
            None => {}
        }
    }
    out
}

/// `s` inside a Swift string literal.
fn swift_text(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => {
                let _ = write!(out, "\\u{{{:x}}}", c as u32);
            }
            c => out.push(c),
        }
    }
    out
}

fn accessor(out: &mut String, row: &Row, name: &str) -> Result<(), String> {
    let args = row.en.args();
    let count = row.en.count();
    // The English the code reads: the plain text, or a plural's `other` variant.
    let ix = match catalog::compile(row.en, row.en)? {
        Compiled::Plain(ix) => ix,
        Compiled::Plural(cases) => cases
            .into_iter()
            .find(|(c, _)| *c == crate::plural::Category::Other)
            .map(|(_, ix)| ix)
            .unwrap_or_default(),
    };
    let params: Vec<String> = args.iter().map(|a| camel(a)).collect();
    let mut doc = String::new();
    let mut text = String::new();
    let mut order = Vec::new();
    for i in &ix {
        match i {
            Ix::Text(t) => {
                doc.push_str(&t.replace('\n', " "));
                text.push_str(&swift_text(t));
            }
            Ix::Arg(n) => {
                let _ = write!(doc, "{{{}}}", args[*n]);
                let _ = write!(text, "\\({})", params[*n]);
                order.push(*n);
            }
        }
    }
    // The default value carries the arguments in index order. When the English shows each
    // once and in that order it is the English; otherwise only the arguments, as Xcode's own
    // generated symbols do.
    if order != (0..args.len()).collect::<Vec<_>>() {
        text = params.iter().map(|p| format!("\\({p})")).collect();
    }
    let resource = format!(
        "LocalizedStringResource(\"{}\", defaultValue: \"{text}\", bundle: L10n.bundle)",
        row.key
    );
    let _ = writeln!(out, "    /// {}", doc.trim_end());
    if args.is_empty() {
        let _ = writeln!(
            out,
            "    public static var {name}: LocalizedStringResource {{\n        {resource}\n    }}\n"
        );
    } else {
        let sig: Vec<String> = args
            .iter()
            .zip(&params)
            .map(|(a, p)| {
                let ty = if Some(a.as_str()) == count {
                    "Int"
                } else {
                    "String"
                };
                format!("{p}: {ty}")
            })
            .collect();
        let _ = writeln!(
            out,
            "    public static func {name}({}) -> String {{\n        String(localized: {resource})\n    }}\n",
            sig.join(", ")
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names() {
        assert_eq!(camel("player_stats_scale_pct"), "playerStatsScalePct");
        assert_eq!(camel("player_4k_x"), "player4kX");
        assert_eq!(swift_text("a \"b\" \\ \n"), r#"a \"b\" \\ \n"#);
    }

    #[test]
    fn format_strings() {
        let ix = vec![Ix::Arg(1), Ix::Text(" at 5% of ".into()), Ix::Arg(0)];
        assert_eq!(format_string(&ix, Some(0), true), "%2$@ at 5%% of %arg");
        assert_eq!(
            format_string(&[Ix::Text("100%".into())], None, false),
            "100%"
        );
    }

    /// A plural whose variants never show the count: a substitution, and the count first.
    #[test]
    fn plural_without_the_number() {
        let src = r#"[{"declarations": ["input count", "input players", "local n = count: plural"],
            "selectors": ["n"], "match": {"n=one": "player {players}", "n=other": "players {players}"}}]"#;
        let en = catalog::parse_message(&crate::json::parse(src).unwrap(), false).unwrap();
        let row = Row {
            key: "fix_players",
            en: &en,
            note: None,
            langs: vec![("en", catalog::compile(&en, &en).unwrap())],
        };
        let json = crate::json::pretty(&entry(&row, &["en".into(), "de".into()]));
        assert!(json.contains(r#""value" : "%#@count@""#), "{json}");
        assert!(json.contains(r#""argNum" : 1"#), "{json}");
        assert!(json.contains(r#""value" : "players %2$@""#), "{json}");
        // German lacks it, so German reads the English.
        assert!(
            json.contains(r#""de" : {"#) && json.contains(r#""state" : "new""#),
            "{json}"
        );
        let mut swift = String::new();
        accessor(&mut swift, &row, "fixPlayers").unwrap();
        assert!(
            swift.contains("func fixPlayers(count: Int, players: String) -> String"),
            "{swift}"
        );
        assert!(
            swift.contains(r#"defaultValue: "\(count)\(players)""#),
            "{swift}"
        );
    }

    #[test]
    fn golden() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixture");
        let (cat, problems) = crate::catalog::load(&root, false);
        assert!(problems.is_empty(), "{problems:?}");
        let files = generate(&cat, &["fix".into()]).unwrap();
        // No phrase and no usage message in `fix`, so no system table.
        assert_eq!(
            files.len(),
            2,
            "{:?}",
            files.iter().map(|f| &f.0).collect::<Vec<_>>()
        );
        for (path, body) in files {
            crate::golden(&format!("apple/{path}"), &body);
        }
    }

    /// The system tables: phrases keyed by English with `${name}` arguments, usage
    /// descriptions keyed by Info.plist key, English filling a language that lacks a message.
    #[test]
    fn system_tables() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixture-apple");
        let (cat, problems) = crate::catalog::load(&root, false);
        assert!(problems.is_empty(), "{problems:?}");
        let files = generate(&cat, &["apple".into()]).unwrap();
        let names: Vec<_> = files.iter().map(|f| f.0.as_str()).collect();
        assert_eq!(
            names,
            [
                "Localizable.xcstrings",
                "L10n.swift",
                "AppShortcuts.xcstrings",
                "InfoPlist.xcstrings"
            ]
        );
        for (path, body) in files.iter().skip(2) {
            crate::golden(&format!("apple-system/{path}"), body);
        }
        let shortcuts = &files[2].1;
        assert!(
            shortcuts.contains(r#""Connect to ${host} in ${applicationName}""#),
            "{shortcuts}"
        );
        assert!(
            shortcuts.contains("Verbinde dich in ${applicationName} mit ${host}"),
            "{shortcuts}"
        );
        // The Bluetooth text fills both keys.
        let plist = &files[3].1;
        assert_eq!(
            plist.matches("Bluetooth lets Punktfunk").count(),
            2,
            "{plist}"
        );
        assert_eq!(
            plist.matches("Bluetooth lässt Punktfunk").count(),
            2,
            "{plist}"
        );
    }

    /// A part with a usage description and no sibling would ship a prompt with no words.
    #[test]
    fn usage_set_is_whole() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixture-apple");
        let (mut cat, problems) = crate::catalog::load(&root, false);
        assert!(problems.is_empty(), "{problems:?}");
        let part = cat.parts.iter_mut().find(|p| p.name == "apple").unwrap();
        part.source
            .entries
            .retain(|e| e.key != "apple_usage_face_id");
        let err = generate(&cat, &["apple".into()]).unwrap_err();
        assert!(err.contains("apple_usage_face_id"), "{err}");
    }
}
