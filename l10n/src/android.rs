//! `pf-l10n android`: Android resources from shared parts. `values/strings.xml` holds the
//! source language, `values-<qualifier>/strings.xml` each other shipped language, and
//! `xml/locales_config.xml` lists them for the per-app language setting.
//!
//! A placeholder becomes `%N$s`, a plural's count `%N$d`, N its place in the English text, so
//! Kotlin passes arguments in that order: `stringResource(R.string.key, a, b)` and
//! `pluralStringResource(R.plurals.key, count, count, b)`. Same input, same bytes.

use std::fmt::Write as _;

use crate::catalog::{Catalog, Compiled, Ix};

const GENERATED: &str = "<!-- Generated by pf-l10n from l10n/messages. Do not edit. -->";

/// `(path under --out, contents)` for each file.
pub fn generate(cat: &Catalog, parts: &[String]) -> Result<Vec<(String, String)>, String> {
    let rows = cat.rows(parts)?;
    let mut files = Vec::new();
    for lang in &cat.shipped {
        let mut xml =
            format!("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n{GENERATED}\n<resources>\n");
        for row in &rows {
            let Some((_, c)) = row.langs.iter().find(|(l, _)| l == lang) else {
                continue;
            };
            let count = row
                .en
                .count()
                .and_then(|n| row.en.args().iter().position(|a| a == n));
            let key = row.key;
            match c {
                Compiled::Plain(ix) => {
                    let formatted = ix.iter().any(|i| matches!(i, Ix::Arg(_)));
                    let percent = ix
                        .iter()
                        .any(|i| matches!(i, Ix::Text(t) if t.contains('%')));
                    let attr = if !formatted && percent {
                        " formatted=\"false\""
                    } else {
                        ""
                    };
                    let _ = writeln!(
                        xml,
                        "    <string name=\"{key}\"{attr}>{}</string>",
                        text(ix, count, formatted)
                    );
                }
                Compiled::Plural(cases) => {
                    let _ = writeln!(xml, "    <plurals name=\"{key}\">");
                    let mut cases: Vec<_> = cases.iter().collect();
                    cases.sort_by_key(|(c, _)| *c);
                    for (cat, ix) in cases {
                        let _ = writeln!(
                            xml,
                            "        <item quantity=\"{}\">{}</item>",
                            cat.name(),
                            text(ix, count, true)
                        );
                    }
                    let _ = writeln!(xml, "    </plurals>");
                }
            }
        }
        xml.push_str("</resources>\n");
        let dir = if *lang == cat.source {
            "values".to_owned()
        } else {
            format!("values-{}", qualifier(lang))
        };
        files.push((format!("{dir}/strings.xml"), xml));
    }
    let mut config = format!(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n{GENERATED}\n<locale-config xmlns:android=\"http://schemas.android.com/apk/res/android\">\n"
    );
    for lang in &cat.shipped {
        let _ = writeln!(config, "    <locale android:name=\"{lang}\"/>");
    }
    config.push_str("</locale-config>\n");
    files.push(("xml/locales_config.xml".into(), config));
    Ok(files)
}

/// The resource directory qualifier: `de`, `pt-rBR`, and `b+zh+Hant` for anything else.
fn qualifier(tag: &str) -> String {
    match tag.split('-').collect::<Vec<_>>().as_slice() {
        [lang] => (*lang).to_owned(),
        [lang, region] if region.len() == 2 && region.bytes().all(|b| b.is_ascii_alphabetic()) => {
            format!("{lang}-r{}", region.to_ascii_uppercase())
        }
        subtags => format!("b+{}", subtags.join("+")),
    }
}

/// One string resource's text. `formatted` is whether Android runs it through a formatter,
/// which doubles a literal `%`. Spaces Android would collapse or trim are kept as ` `.
fn text(ix: &[Ix], count: Option<usize>, formatted: bool) -> String {
    enum Atom {
        Char(char),
        Spec(String),
    }
    let atoms: Vec<Atom> = ix
        .iter()
        .flat_map(|i| match i {
            Ix::Text(t) => t.chars().map(Atom::Char).collect(),
            Ix::Arg(n) => vec![Atom::Spec(format!(
                "%{}${}",
                n + 1,
                if Some(*n) == count { 'd' } else { 's' }
            ))],
        })
        .collect();
    let mut out = String::new();
    for (i, atom) in atoms.iter().enumerate() {
        let c = match atom {
            Atom::Spec(s) => {
                out.push_str(s);
                continue;
            }
            Atom::Char(c) => *c,
        };
        let edge_space = i == 0 || i + 1 == atoms.len() || matches!(atoms[i - 1], Atom::Char(' '));
        match c {
            '\\' => out.push_str("\\\\"),
            '\'' => out.push_str("\\'"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '%' if formatted => out.push_str("%%"),
            '@' | '?' if i == 0 => {
                out.push('\\');
                out.push(c);
            }
            ' ' if edge_space => out.push_str("\\u0020"),
            c => out.push(c),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::catalog;

    #[test]
    fn qualifiers() {
        assert_eq!(qualifier("de"), "de");
        assert_eq!(qualifier("pt-BR"), "pt-rBR");
        assert_eq!(qualifier("zh-Hant"), "b+zh+Hant");
        assert_eq!(qualifier("es-419"), "b+es+419");
    }

    #[test]
    fn escapes() {
        let t = |s: &str| vec![Ix::Text(s.into())];
        assert_eq!(
            text(&t("Don't \"x\" & <y> \\ 5%"), None, false),
            r#"Don\'t \"x\" &amp; &lt;y&gt; \\ 5%"#
        );
        assert_eq!(text(&t("@home ?x"), None, false), r"\@home ?x");
        assert_eq!(text(&t("a\nb  c "), None, false), "a\\nb \\u0020c\\u0020");
        let ix = vec![Ix::Arg(1), Ix::Text(" at 5% of ".into()), Ix::Arg(0)];
        assert_eq!(text(&ix, Some(0), true), "%2$s at 5%% of %1$d");
    }

    #[test]
    fn golden() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixture");
        let (cat, problems) = catalog::load(&root, false);
        assert!(problems.is_empty(), "{problems:?}");
        for (path, body) in generate(&cat, &["fix".into()]).unwrap() {
            crate::golden(&format!("android/{path}"), &body);
        }
    }
}
