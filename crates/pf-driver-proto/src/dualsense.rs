/// Pairing reply (`0x09`) for pad `index` presented as `device_type`. Its low MAC octet is
/// [`crate::gamepad::ps_mac_low`], the octet that ends the pad's USB serial. `hid-playstation`
/// adopts the MAC as HID `uniq`, and SDL and Steam merge two pads that share one.
pub fn pairing_reply(device_type: u8, index: u8) -> [u8; 20] {
    let mut r = FEATURE_PAIRING;
    r[1] = crate::gamepad::ps_mac_low(device_type, index);
    r
}
