/// Pairing reply (`0x12`) for pad `index`. Its low MAC octet is [`crate::gamepad::ps_mac_low`].
pub fn pairing_reply(index: u8) -> [u8; 16] {
    let mut r = FEATURE_PAIRING;
    r[1] = crate::gamepad::ps_mac_low(crate::gamepad::DEVTYPE_DUALSHOCK4, index);
    r
}
