//! Static screen: the app's own license + the third-party software notices (reached from
//! Settings).

use super::style::*;
use super::{AppCtx, AsyncSetState, Screen};
use pf_fluent::{Palette, Token};
use pf_l10n::{client, common, desktop};
use std::sync::Arc;
use windows_reactor::*;

/// punktfunk's own license (MIT OR Apache-2.0).
const APP_LICENSE: &str = concat!(
    include_str!("../../../../LICENSE-MIT"),
    "\n\n================================ Apache-2.0 ================================\n\n",
    include_str!("../../../../LICENSE-APACHE"),
);
/// Third-party software notices for the Rust crates THIS CLIENT links — the shell, the
/// session streamer and the headless CLI (generated by scripts/gen-third-party-notices.sh;
/// the MSIX ships the same file under licenses/).
///
/// Deliberately the client-scoped file and not the workspace-wide one at the repo root: the
/// root file covers the whole workspace, so it would attribute crates this app never bundles
/// — a false statement to the user's face, three lines under a card saying otherwise.
const THIRD_PARTY_NOTICES: &str = include_str!("../../THIRD-PARTY-NOTICES.txt");

pub(crate) fn licenses_page(
    pal: &Palette,
    ctx: &Arc<AppCtx>,
    set_screen: &AsyncSetState<Screen>,
) -> View {
    let back_btn = icon_button("arrow-left", common::common_back())
        .style(ButtonStyle::Accent)
        .on_click({
            let (c, ss) = (ctx.clone(), set_screen.clone());
            move || {
                // Back RE-ENTERS the settings page — re-base its snapshot on the file, same
                // as the hosts page's Settings button (see settings::refresh_snapshot).
                super::settings::refresh_snapshot(&c);
                ss.call(Screen::Settings)
            }
        });

    let app_card = card(
        vstack((
            text("Punktfunk")
                .font_size(15.0)
                .font_weight(FontWeight::SEMI_BOLD),
            text(client::about_license_statement())
                .font_size(12.0)
                .text_wrapping(TextWrapping::Wrap)
                .foreground(pal.get(Token::SecondaryText)),
            text(APP_LICENSE)
                .font_size(11.0)
                .text_wrapping(TextWrapping::Wrap)
                .foreground(pal.get(Token::SecondaryText)),
        ))
        .spacing(8.0),
    );

    let natives_card = card(
        vstack((
            text(desktop::desktop_licenses_bundled_components())
                .font_size(15.0)
                .font_weight(FontWeight::SEMI_BOLD),
            text(desktop::desktop_licenses_bundled_body())
                .font_size(12.0)
                .text_wrapping(TextWrapping::Wrap)
                .foreground(pal.get(Token::SecondaryText)),
        ))
        .spacing(8.0),
    );

    let notices_card = card(
        vstack((
            text(desktop::desktop_licenses_rust_crates())
                .font_size(15.0)
                .font_weight(FontWeight::SEMI_BOLD),
            text(THIRD_PARTY_NOTICES)
                .font_size(11.0)
                .text_wrapping(TextWrapping::Wrap)
                .foreground(pal.get(Token::SecondaryText)),
        ))
        .spacing(8.0),
    );

    page(vec![
        page_header(client::about_licenses_title(), back_btn),
        section(pal, "PUNKTFUNK"),
        app_card.into(),
        section(
            pal,
            &desktop::desktop_licenses_section_bundled().to_uppercase(),
        ),
        natives_card.into(),
        section(
            pal,
            &desktop::desktop_licenses_section_open_source().to_uppercase(),
        ),
        notices_card.into(),
    ])
}
